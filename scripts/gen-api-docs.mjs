#!/usr/bin/env node
// Generates docs/API.md from the committed IDLs (packages/viwoapp-sdk/src/idl), so the
// instruction reference can never drift from the programs. Run after scripts/sync-idl.mjs.
import { readFileSync, writeFileSync } from "node:fs";

const PROGRAMS = [
  ["vcoin_token", "vcoin-token"],
  ["vevcoin_token", "vevcoin-token"],
  ["staking_protocol", "staking-protocol"],
  ["private_poll", "private-poll"],
  ["sscre_protocol", "sscre-protocol"],
  ["gasless_protocol", "gasless-protocol"],
  ["five_a_protocol", "five-a-protocol"],
  ["identity_protocol", "identity-protocol"],
  ["content_registry", "content-registry"],
  ["vilink_protocol", "vilink-protocol"],
];

function typeName(t) {
  if (typeof t === "string") return t === "pubkey" ? "Pubkey" : t;
  if (t.array) return `[${typeName(t.array[0])}; ${t.array[1]}]`;
  if (t.vec) return `Vec<${typeName(t.vec)}>`;
  if (t.option) return `Option<${typeName(t.option)}>`;
  if (t.defined) return t.defined.name;
  return JSON.stringify(t);
}

function accountRows(accounts, prefix = "") {
  return accounts.flatMap((a) => {
    if (a.accounts) return accountRows(a.accounts, `${prefix}${a.name}.`);
    const flags = [a.signer && "signer", a.writable && "writable", a.optional && "optional", a.pda && "PDA", a.address && `= \`${a.address}\``]
      .filter(Boolean)
      .join(", ");
    return [`| \`${prefix}${a.name}\` | ${flags} | ${(a.docs ?? []).join(" ")} |`];
  });
}

const out = [
  "# Program API reference",
  "",
  "Generated by `scripts/gen-api-docs.mjs` from the IDLs in `packages/viwoapp-sdk/src/idl` (which CI",
  "checks against `anchor build`). Do not edit by hand. Behaviour, invariants and admin powers are",
  "described per program in `docs/programs/`.",
  "",
];

for (const [file, title] of PROGRAMS) {
  const idl = JSON.parse(readFileSync(`packages/viwoapp-sdk/src/idl/${file}.json`, "utf8"));
  out.push(`## ${title}`, "", `Program id: \`${idl.address}\``, "");
  out.push("### Instructions", "");
  for (const ix of idl.instructions) {
    const args = ix.args.map((a) => `${a.name}: ${typeName(a.type)}`).join(", ");
    out.push(`#### \`${ix.name}(${args})\``, "");
    if (ix.docs?.length) out.push(ix.docs.join(" "), "");
    out.push("| Account | Flags | Notes |", "|---|---|---|", ...accountRows(ix.accounts), "");
  }
  if (idl.accounts?.length) {
    out.push("### Accounts", "", idl.accounts.map((a) => `\`${a.name}\``).join(", "), "");
  }
  if (idl.events?.length) {
    out.push("### Events", "", idl.events.map((e) => `\`${e.name}\``).join(", "), "");
  }
  if (idl.errors?.length) {
    out.push("### Errors", "", "| Code | Name | Message |", "|---|---|---|");
    for (const e of idl.errors) out.push(`| ${e.code} | \`${e.name}\` | ${e.msg ?? ""} |`);
    out.push("");
  }
}

writeFileSync("docs/API.md", out.join("\n"));
console.log(`wrote docs/API.md (${out.length} lines)`);
